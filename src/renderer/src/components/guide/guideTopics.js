/** Flattens a block to the text a search should look through (inline markers removed). */
function blockText(block) {
  const parts = []
  if (block.text) parts.push(block.text)
  if (block.label) parts.push(block.label)
  if (block.items) parts.push(...block.items)
  if (block.head) parts.push(...block.head)
  if (block.rows) parts.push(...block.rows.flat())
  return parts.join(' ')
}

export function plainGuideText(text) {
  return String(text).replace(/\*\*/g, '').replace(/\[\[|\]\]|\{\{|\}\}/g, '')
}

export function topicSearchText(topic) {
  return plainGuideText([topic.title, topic.blurb, ...topic.blocks.map(blockText)].join(' ')).toLowerCase()
}

/** The topics whose title or text contain every word of `query` (all topics for an empty one). */
export function searchTopics(query, topics = GUIDE_TOPICS) {
  const words = String(query || '').toLowerCase().split(/\s+/).filter(Boolean)
  if (words.length === 0) return topics
  return topics.filter(topic => {
    const haystack = topicSearchText(topic)
    return words.every(word => haystack.includes(word))
  })
}
