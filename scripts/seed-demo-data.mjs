// Fills a throwaway directory with a polished sample history, for demos, screenshots and videos.
//
//   npm run seed:demo -- <directory>                  -> 210 days, today left empty
//   npm run seed:demo -- <directory> --days 365       -> a longer history
//   npm run seed:demo -- <directory> --with-today     -> today is filled in as well
//
// Run the app on it with TESSERA_USER_DATA_DIR / TESSERA_DATA_DIR pointing at throwaway folders
// (see docs/ENGINEERING_GUIDE.md). The target is overwritten, so the script only writes into an
// empty directory or one a seed script made before, and never into the real default data.
// scripts/seed-dev-data.mjs is the test fixture (with an extreme value on purpose); this is the
// natural-looking one.
import fs from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { buildDemoData } from './lib/demo-data.mjs'
import { MARKER, assertSafeTarget, writeJson } from './lib/seed-target.mjs'

function parseArguments(argv) {
  const options = { days: 210, withToday: false, directory: '' }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--with-today') options.withToday = true
    else if (argument === '--days') options.days = Number.parseInt(argv[(index += 1)] || '', 10)
    else if (argument.startsWith('--')) throw new Error(`Unknown option ${argument}`)
    else options.directory = argument
  }
  if (!options.directory) throw new Error('Usage: npm run seed:demo -- <directory> [--days N] [--with-today]')
  if (!Number.isInteger(options.days) || options.days < 7 || options.days > 3660) {
    throw new Error('--days must be a whole number between 7 and 3660')
  }
  return options
}

async function main() {
  const { directory, days, withToday } = parseArguments(process.argv.slice(2))
  const target = path.resolve(directory)
  await assertSafeTarget(target)
  await fs.rm(target, { recursive: true, force: true })
  await fs.mkdir(path.join(target, 'backups'), { recursive: true })
  await fs.writeFile(path.join(target, MARKER), 'Sample data generated by scripts/seed-demo-data.mjs\n')

  const data = buildDemoData({ days, withToday })
  await writeJson(path.join(target, 'sections.json'), data.sections)
  for (const day of data.days) {
    await writeJson(path.join(target, day.year, day.month, `${day.day}.json`), day.entries)
  }
  await writeJson(path.join(target, 'notes', 'index.json'), data.notes.map(({ content: _content, ...meta }) => meta))
  for (const note of data.notes) await writeJson(path.join(target, 'notes', `${note.id}.json`), note)
  await writeJson(path.join(target, 'metadata.json'), data.metadata)

  console.log(`Seeded ${data.days.length} days, ${data.notes.length} notes and ${data.metadata.analytics.length} charts into ${target}`)
}

main().catch(error => {
  console.error(error.message)
  process.exitCode = 1
})
